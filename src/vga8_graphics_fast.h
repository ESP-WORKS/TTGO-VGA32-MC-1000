inline void packGraphicsRow(uint8_t *dst, const uint8_t *src,
                            int width, int bpp, uint8_t border) {
  if (!dst || !src) return;
  const uint32_t fill = packedSolid(border);
  for (int i = 0; i < 4; ++i) storeTriple(dst + i*3, fill);
  uint8_t *out = dst + 12;
  if (bpp == 1 && width == 256) {
    for (int b = 0; b < 32; ++b, out += 3)
      storeTriple(out, kMono1x[src[b]]);
  } else if (bpp == 1 && width == 128) {
    for (int b = 0; b < 16; ++b, out += 6) {
      const uint8_t value = src[b];
      storeTriple(out, kMono2x[value >> 4]);
      storeTriple(out + 3, kMono2x[value & 15]);
    }
  } else if (bpp == 2 && width == 128) {
    for (int b = 0; b < 32; ++b, out += 3)
      storeTriple(out, kColor2x[src[b]]);
  } else if (bpp == 2 && width == 64) {
    for (int b = 0; b < 16; ++b, out += 6) {
      const uint8_t value = src[b];
      storeTriple(out, kColor4x[value >> 4]);
      storeTriple(out + 3, kColor4x[value & 15]);
    }
  }
  for (int i = 0; i < 4; ++i) storeTriple(dst + 108 + i*3, fill);
}
